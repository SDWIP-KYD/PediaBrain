export function searchDrugs(query: string): DrugDefinition[] {
  if (!query.trim()) return drugs;
  const q = query.toLowerCase();
  return drugs.filter(
    (d) =>
      d.name.toLowerCase().includes(q) ||
      d.brandNames.some((b) => b.toLowerCase().includes(q)) ||
      d.category.toLowerCase().includes(q) ||
      d.subcategory.toLowerCase().includes(q)
  );
}

export function getDrugsByCategory(category: DrugCategory): DrugDefinition[] {
  return drugs.filter((d) => d.category === category);
}

export function getDrugById(id: string): DrugDefinition | undefined {
  return drugs.find((d) => d.id === id);
}
