export type ChartIndicator =
  | "weight-for-age"
  | "height-for-age"
  | "head-circumference-for-age";

export function getDataset(
  indicator: ChartIndicator,
  sex: "L" | "P"
): LMSRow[] {
  const isMale = sex === "L";
  switch (indicator) {
    case "weight-for-age":
      return isMale ? weightForAgeBoys : weightForAgeGirls;
    case "height-for-age":
      return isMale ? heightForAgeBoys : heightForAgeGirls;
    case "head-circumference-for-age":
      return isMale ? headCircForAgeBoys : headCircForAgeGirls;
  }
}
