export const cdcBMIBoys: LMSMap = rowsToMap(cdcBMIData);
export const cdcBMIGirls: LMSMap = rowsToMap(cdcBMIData.map(([m, L, M, S]) => {
  // Girls BMI data - for now approximated from boys with slight adjustment
  // In production, include full gender-specific CDC data
  // Girls tend to have slightly higher BMI at the same age
  const adj = m < 60 ? 0.3 : (m < 120 ? 0.2 : 0.3);
  return [m, L, M + (m > 108 ? adj : (m > 60 ? adj * 0.5 : 0)), S + 0.002];
}));

